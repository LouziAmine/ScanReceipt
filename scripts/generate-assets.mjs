// Generates every web, iOS and Android icon / splash file from the vector logo in assets/logo.svg.
//
// Run from the project root after changing the logo:  npm run assets
// The logo must stay a 1024 x 1024 viewBox of plain <path fill d> elements (optional fill-opacity), on a transparent
// background: the same paths become SVG files for the web and iOS, and an Android VectorDrawable.
// Only the files a platform cannot take as a vector are rasterized: the iOS App Store icon and the iOS / PWA fallbacks.
import { readFileSync, writeFileSync } from 'node:fs';
import { Resvg } from '@resvg/resvg-js';

const NAVY = '#0B2B3A';
const TILE = '#11394B';
const SIZE = 1024;
const CENTER = SIZE / 2;
/** The receipt is drawn slightly above the canvas center; this moves it back when the mark is scaled alone. */
const MARK_CENTER_Y = 501.5;

const RES = 'android/app/src/main/res';
const IOS = 'ios/App/App/Assets.xcassets';

const paths = [...readFileSync('assets/logo.svg', 'utf8').matchAll(/<path\b([^>]*)\/>/g)].map(([, attrs]) => {
  const attr = (name) => attrs.match(new RegExp(`\\b${name}="([^"]*)"`))?.[1];
  return { fill: attr('fill'), opacity: attr('fill-opacity'), d: attr('d') };
});
if (paths.length === 0 || paths.some((p) => !p.fill || !p.d)) {
  throw new Error('assets/logo.svg must contain only <path fill="..." d="..."/> elements');
}

/** Rounded square path, so Android (no <rect>) and the web share one shape. */
const roundedSquare = (x, size, r) =>
  `M${x + r} ${x}H${x + size - r}A${r} ${r} 0 0 1 ${x + size} ${x + r}V${x + size - r}` +
  `A${r} ${r} 0 0 1 ${x + size - r} ${x + size}H${x + r}A${r} ${r} 0 0 1 ${x} ${x + size - r}` +
  `V${x + r}A${r} ${r} 0 0 1 ${x + r} ${x}Z`;
const circle = `M0 ${CENTER}A${CENTER} ${CENTER} 0 1 1 ${SIZE} ${CENTER}A${CENTER} ${CENTER} 0 1 1 0 ${CENTER}Z`;

// ---------- SVG ----------

const svgPaths = (shapes) =>
  shapes
    .map(({ fill, opacity, d }) => `<path fill="${fill}"${opacity ? ` fill-opacity="${opacity}"` : ''} d="${d}"/>`)
    .join('');

const svg = (viewBox, body) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${viewBox} ${viewBox}">${body}</svg>\n`;

/** The app icon: the logo on a navy background, either square (stores, PWA) or with rounded corners (browser tab). */
const iconSvg = (radius = 0) =>
  svg(SIZE, svgPaths([{ fill: NAVY, d: radius ? roundedSquare(0, SIZE, radius) : `M0 0H${SIZE}V${SIZE}H0Z` }, ...paths]));

/** iOS launch screen: a rounded tile with the logo, centered on a navy square the storyboard crops to the screen. */
const splashSvg = () => {
  const canvas = 2732;
  const tile = 600;
  const offset = (canvas - tile) / 2;
  const scale = tile / SIZE;
  return svg(
    canvas,
    `<path fill="${NAVY}" d="M0 0H${canvas}V${canvas}H0Z"/>` +
      `<g transform="translate(${offset} ${offset}) scale(${scale})">` +
      svgPaths([{ fill: TILE, d: roundedSquare(0, SIZE, 225) }, ...paths]) +
      '</g>',
  );
};

// ---------- Android VectorDrawable ----------

const vectorPaths = (shapes, indent) =>
  shapes
    .map(
      ({ fill, opacity, d }) =>
        `${indent}<path\n${indent}    android:fillColor="${fill}"\n` +
        (opacity ? `${indent}    android:fillAlpha="${opacity}"\n` : '') +
        `${indent}    android:pathData="${d}" />`,
    )
    .join('\n');

const vector = (dp, body) =>
  `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/generate-assets.mjs from assets/logo.svg; do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="${dp}dp"
    android:height="${dp}dp"
    android:viewportWidth="${SIZE}"
    android:viewportHeight="${SIZE}">
${body}
</vector>
`;

/** Adaptive icon foreground: the logo shrunk into the 66 / 108 safe zone that every launcher mask keeps. */
const foregroundVector = () => {
  const scale = 0.668;
  return vector(
    108,
    `    <group
        android:pivotX="${CENTER}"
        android:pivotY="${CENTER}"
        android:scaleX="${scale}"
        android:scaleY="${scale}"
        android:translateY="${((CENTER - MARK_CENTER_Y) * scale).toFixed(2)}">
${vectorPaths(paths, '        ')}
    </group>`,
  );
};

const write = (path, content) => {
  writeFileSync(path, content);
  console.log(`${path}  ${content.length} B`);
};

const png = (path, svgSource, size) => {
  const image = new Resvg(svgSource, { fitTo: { mode: 'width', value: size } }).render().asPng();
  write(path, image);
};

// Web: vector favicon and PWA icon. iOS Safari still needs a PNG home-screen icon, and a 512 px PNG keeps older
// Android browsers able to install the PWA.
write('public/favicon.svg', iconSvg(225));
write('public/icon.svg', iconSvg());
png('public/apple-touch-icon.png', iconSvg(), 180);
png('public/icon-512.png', iconSvg(), 512);

// Android: launcher icons and splash are VectorDrawables; one file serves every screen density.
write(`${RES}/drawable/ic_launcher_foreground.xml`, foregroundVector());
write(`${RES}/mipmap-anydpi/ic_launcher.xml`, vector(48, vectorPaths([{ fill: NAVY, d: roundedSquare(0, SIZE, 180) }, ...paths], '    ')));
write(`${RES}/mipmap-anydpi/ic_launcher_round.xml`, vector(48, vectorPaths([{ fill: NAVY, d: circle }, ...paths], '    ')));
write(`${RES}/drawable/splash_logo.xml`, vector(200, vectorPaths([{ fill: TILE, d: roundedSquare(0, SIZE, 225) }, ...paths], '    ')));

// iOS: the launch image stays a vector in the asset catalog; the App Store only accepts an opaque 1024 px PNG icon.
write(`${IOS}/Splash.imageset/splash.svg`, splashSvg());
png(`${IOS}/AppIcon.appiconset/AppIcon-512@2x.png`, iconSvg(), 1024);
